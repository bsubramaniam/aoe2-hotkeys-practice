function actionId(stringId: number): string {
  return legacyActionIds.get(stringId) ?? `hotkey_${stringId}`;
}

const actionByStringId = new Map<number, HotkeyActionDefinition>(
  [...new Map([...actionData, ...CURRENT_HOTKEY_LABELS])].map(([stringId, label]) => [
    stringId,
    { id: actionId(stringId), label, stringId },
  ]),
);

export const HOTKEY_ACTIONS = new Map<string, HotkeyActionDefinition>(
  [...actionByStringId.values()].map((action) => [action.id, action]),
);

export function getHotkeyAction(id: string): HotkeyActionDefinition | undefined {
  const known = HOTKEY_ACTIONS.get(id);
  if (known) return known;
  const match = /^hotkey_(\d+)$/.exec(id);
  if (!match) return undefined;
  const stringId = Number(match[1]);
  if (!Number.isSafeInteger(stringId) || stringId <= 0) return undefined;
  return { id, label: `Hotkey action ${stringId}`, stringId };
}

export function actionsForStringIds(stringIds: Iterable<number>): HotkeyActionDefinition[] {
  const actions = new Map<number, HotkeyActionDefinition>(actionByStringId);
  for (const stringId of stringIds) {
    if (!actions.has(stringId)) {
      actions.set(stringId, {
        id: actionId(stringId),
        label: `Hotkey action ${stringId}`,
        stringId,
      });
    }
  }
  return [...actions.values()].sort((left, right) =>
    left.label.localeCompare(right.label) || left.stringId - right.stringId
  );
}
