import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parseHotkeyFiles } from "../src/hotkey-file.ts";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(repositoryRoot, "src", "default-profile.ts");
const inputNames = ["Base.hkp", "Hotkeys.hkp"];

const files = inputNames.map((name) => ({
  name,
  buffer: Uint8Array.from(readFileSync(join(repositoryRoot, name))).buffer,
}));
const profile = parseHotkeyFiles(files);
const rows = [];

for (const [stringId, bindings] of [...profile.bindings].sort((left, right) => left[0] - right[0])) {
  const binding = bindings[0];
  if (!binding || bindings.length !== 1) {
    throw new Error(`Expected exactly one default binding for command ${stringId}.`);
  }
  const modifiers = (binding.ctrl ? 1 : 0) | (binding.alt ? 2 : 0) | (binding.shift ? 4 : 0);
  rows.push(`  [${stringId}, ${JSON.stringify(binding.key)}, ${modifiers}],`);
}

const output = [
  "// Generated by npm run generate:default-profile. Do not edit manually.",
  'import type { HotkeyBinding, HotkeyProfile } from "./hotkey-file";',
  "",
  "type DefaultBinding = readonly [stringId: number, key: string, modifiers: number];",
  "",
  "// Modifier bit flags: Ctrl = 1, Alt = 2, Shift = 4.",
  "// This table contains functional bindings only; it does not embed an HKI/HKP file.",
  "const DEFAULT_BINDINGS = [",
  ...rows,
  "] as const satisfies readonly DefaultBinding[];",
  "",
  "export function createDefaultProfile(): HotkeyProfile {",
  "  const bindings = new Map<number, HotkeyBinding[]>();",
  "  for (const [stringId, key, modifiers] of DEFAULT_BINDINGS) {",
  "    bindings.set(stringId, [{",
  "      key,",
  "      ctrl: (modifiers & 1) !== 0,",
  "      alt: (modifiers & 2) !== 0,",
  "      shift: (modifiers & 4) !== 0,",
  "    }]);",
  "  }",
  '  return { files: ["Built-in default mapping"], bindings };',
  "}",
  "",
].join("\n");

writeFileSync(outputPath, output, "utf8");
console.log(`Generated ${profile.bindings.size} default bindings in ${outputPath}.`);
